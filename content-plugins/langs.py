def load_keys(strings_xml: Path):
    import re
    text = strings_xml.read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r'<string name="((?:common|filetree)_[a-z_0-9]+)"[^>]*>(.*?)</string>', text, re.S):
        out.append((m.group(1), m.group(2)))
    return out


def check(keys):
    """Platzhalter müssen zum englischen Original passen; liefert je Paket die gültigen Übersetzungen."""
    import re
    ph = lambda s: sorted(re.findall(r"%\d\$[sd]", s))
    en = dict(keys)
    out = {}
    for pid, loc, name, vals in PACKS:
        ok = {}
        for k, v in vals.items():
            if k not in en:
                continue  # Schlüssel gibt es in der App nicht mehr
            assert ph(en[k]) == ph(v), f"{pid}/{k}: Platzhalter {ph(en[k])} != {ph(v)} ({v})"
            ok[k] = v
        assert len(ok) >= len(vals) * 0.8, f"{pid}: nur {len(ok)} von {len(vals)} Schlüsseln noch vorhanden"
        out[pid] = ok
    return out
