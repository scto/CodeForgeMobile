#!/usr/bin/env python3
"""Erzeugt eine README.md aus dem Projekt (Name, Module, Technik, SDK-Werte, Build-Befehle, Lizenz).
Eingabe: de (Standard) oder en. Eine vorhandene README.md wird nie überschrieben: dann entsteht README.generated.md."""
import os, re
from common import args, read, write, walk, rel

TEXT = {
    "de": dict(desc="Beschreibung folgt.", tech="Technik", modules="Module", build="Bauen und testen", lic="Lizenz",
               pkg="Paket", sdk="SDK", none="Einzelmodul", licf="Siehe [LICENSE](LICENSE).", nolic="Noch keine Lizenz festgelegt.",
               hint="<!-- Von CodeForge (PT → README.md erstellen) erzeugt – bitte Beschreibung ergänzen. -->"),
    "en": dict(desc="Description to follow.", tech="Tech stack", modules="Modules", build="Build and test", lic="License",
               pkg="Package", sdk="SDK", none="Single module", licf="See [LICENSE](LICENSE).", nolic="No license chosen yet.",
               hint="<!-- Generated by CodeForge (PT → Create README.md) – please add a description. -->"),
}


def first(pattern, text, default=None):
    m = re.search(pattern, text)
    return m.group(1) if m else default


def main():
    project, lang = args()
    lang = lang.lower() or "de"
    if lang not in TEXT:
        raise SystemExit("Sprache: de oder en")
    t = TEXT[lang]
    files = list(walk(project, names={"build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts"}))
    blob = "\n".join(read(p) for p in files)
    low = blob.lower()
    catalog_path = os.path.join(project, "gradle", "libs.versions.toml")
    catalog = read(catalog_path).lower() if os.path.isfile(catalog_path) else ""
    settings = next((read(p) for p in files if os.path.basename(p).startswith("settings.gradle")), "")

    name = first(r'rootProject\.name\s*=\s*["\']([^"\']+)', settings) or os.path.basename(project)
    modules = sorted(set(re.findall(r'["\']:([\w:.\-]+)["\']', settings)))
    app_id = first(r'applicationId\s*=?\s*["\']([^"\']+)', blob)
    min_sdk = first(r'minSdk\w*\s*[=(]?\s*(\d+)', blob)
    target_sdk = first(r'targetSdk\w*\s*[=(]?\s*(\d+)', blob)

    both = low + "\n" + catalog
    tech = []
    if "kotlin" in both:
        tech.append("Kotlin")
    if "compose" in both:
        tech.append("Jetpack Compose" + (" · Material 3" if "material3" in both else ""))
    if "hilt" in both or "dagger" in both:
        tech.append("Hilt")
    if re.search(r"\broom\b|androidx\.room", both):
        tech.append("Room")
    if "coroutines" in both:
        tech.append("Coroutines/Flow")
    if catalog:
        tech.append("Gradle Kotlin DSL + Version Catalog" if any(p.endswith(".kts") for p in files) else "Gradle + Version Catalog")
    elif files:
        tech.append("Gradle")

    gradle = "./gradlew" if os.path.isfile(os.path.join(project, "gradlew")) else "gradle"
    has_tests = any("/src/test/" in p.replace("\\", "/") or "/src/androidTest/" in p.replace("\\", "/")
                    for p in walk(project, exts={"kt", "java"}))
    has_license = any(os.path.isfile(os.path.join(project, f)) for f in ("LICENSE", "LICENSE.md", "LICENSE.txt"))

    facts = []
    if app_id:
        facts.append(f"- {t['pkg']}: `{app_id}`")
    if min_sdk or target_sdk:
        facts.append(f"- {t['sdk']}: min {min_sdk or '?'} / target {target_sdk or '?'}")

    out = [f"# {name}", "", t["hint"], "", t["desc"], ""]
    if tech or facts:
        out += [f"## {t['tech']}", ""] + [f"- {x}" for x in tech] + facts + [""]
    out += [f"## {t['modules']}", ""]
    out += [f"- `:{m}`" for m in modules] if modules else [f"- {t['none']}"]
    out += ["", f"## {t['build']}", "", "```bash", f"{gradle} assembleDebug"]
    if has_tests:
        out.append(f"{gradle} testDebugUnitTest")
    out += ["```", "", f"## {t['lic']}", "", t["licf"] if has_license else t["nolic"], ""]

    target = os.path.join(project, "README.md")
    if os.path.exists(target):
        target = os.path.join(project, "README.generated.md")
    write(target, "\n".join(out))
    print(f"{rel(target, project)} geschrieben ({len(modules)} Module, {len(tech)} Techniken erkannt)")
    if os.path.basename(target) != "README.md":
        print("README.md existiert bereits und wurde nicht angetastet.")


main()
